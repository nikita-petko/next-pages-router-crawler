type TTempFinanceIconProps = {
  /** ISO country (`GB`) or currency (`GBP`). Falls back to locale / browser region. */
  countryOrCurrency?: string | null;
};

const shouldUseGbpIcon = (
  countryOrCurrency: string | null | undefined,
  locale: string | null | undefined,
): boolean => {
  // Explicit country/currency wins (billing address GB → GBP).
  if (countryOrCurrency != null && countryOrCurrency !== '') {
    return usesGbpCurrency(countryOrCurrency);
  }
  return usesGbpCurrency(locale) || detectGbpFromBrowser();
};

export const TempFinanceIcon = ({ countryOrCurrency }: TTempFinanceIconProps) => {
  const { locale } = useLocalization();
  return shouldUseGbpIcon(countryOrCurrency, locale) ? (
    <TempFinanceGbpIcon />
  ) : (
    <TempFinanceDollarIcon />
  );
};

export const TempFinanceFillIcon = ({ countryOrCurrency }: TTempFinanceIconProps) => {
  const { locale } = useLocalization();
  return shouldUseGbpIcon(countryOrCurrency, locale) ? (
    <TempFinanceGbpFillIcon />
  ) : (
    <TempFinanceDollarFillIcon />
  );
};

